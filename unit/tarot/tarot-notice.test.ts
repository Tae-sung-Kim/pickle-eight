import { describe, expect, it } from 'vitest';
import * as notice from '@/features/tarot/constants/tarot-notice.constant';

// 승인 원문은 리터럴로 적는다. 상수를 고치면 이 파일도 함께 고쳐야 한다 (사용자 승인 필요).
describe('타로 고지 원문 (글자 단위)', () => {
  it('상시 면책과 결과 하단 면책이 승인 원문과 같다', () => {
    expect(notice.TAROT_DISCLAIMER_TEXT).toBe(
      '본 타로 서비스는 오락 및 엔터테인먼트 목적으로 제공되며, 전문적인 법률·의학·재정적 조언을 대신할 수 없습니다.'
    );
    expect(notice.TAROT_RESULT_DISCLAIMER_TEXT).toBe(
      '타로는 오락과 자기 성찰을 위한 콘텐츠이며, 결과는 미래를 예측하거나 보장하지 않습니다. 건강·법률·투자 등 중요한 결정은 전문가와 상담하시기 바랍니다.'
    );
  });

  it('AC-23: 전문가 안내, 민감 입력 안내, 질문 용도 안내가 승인 원문과 같다', () => {
    expect(notice.TAROT_EXPERT_NOTICE_TEXT).toBe(
      '건강, 법률, 투자와 관련된 고민은 전문가와 상담하시기 바랍니다. 타로 결과는 참고용입니다.'
    );
    expect(notice.TAROT_SENSITIVE_INPUT_NOTICE).toBe(
      '입력한 질문은 서버나 이 기기에 저장되지 않습니다. 상대방 이름·연락처 같은 개인정보나 민감한 내용은 입력하지 않으시기 바랍니다.'
    );
    expect(notice.TAROT_QUESTION_USAGE_NOTICE).toBe(
      '입력한 내용은 카드 선택과 해석에 쓰이지 않으며, 위기 안내가 필요한지 확인하는 데만 쓰입니다.'
    );
  });

  it('상세 안내 8항이 승인 원문과 같고 순서도 같다', () => {
    expect(notice.TAROT_DETAIL_NOTICE_ITEMS).toEqual([
      '본 서비스는 오락과 자기 성찰 목적으로 제공됩니다.',
      '타로 결과는 과학적으로 입증된 것이 아니며, 미래나 결과를 예측하거나 보장하지 않습니다.',
      '건강, 법률, 투자, 심리 위기와 관련된 문제는 해당 분야 전문가와 상담하시기 바랍니다.',
      '타로 결과만으로 중요한 결정을 내리지 않으시기 바랍니다.',
      '본 서비스는 특정 타로 덱 제작사나 출판사와 제휴·후원 관계가 없습니다.',
      '카드는 무작위로 뽑히며 질문 내용과 관계가 없습니다.',
      '입력한 질문은 서버나 이 기기에 저장되지 않습니다. 상대방 이름·연락처 같은 개인정보나 민감한 내용은 입력하지 않으시기 바랍니다.',
      '오늘의 카드는 날짜와 카드 정보만 이 기기에 저장됩니다. 다른 기기에서는 다른 카드가 나올 수 있습니다.',
    ]);
  });
});
